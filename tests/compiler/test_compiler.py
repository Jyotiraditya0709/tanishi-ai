"""L1 exam: the Learning Compiler, passes 1, 3 and 4.

Written from the spec (graph.yaml node L1) and the decisions of the nodes it builds on (CS2, CS3, CS5, AR1, OBS3),
without reading any compiler code. The spec names files but no function names, so the readings this exam pins are
listed in build/memory/open-problems/L1-exam-assumptions.md. Where the implementer disagrees, they write to the
human there; they do not edit this file.

Pinned surface (everything else is free):

  tanishi.compiler.experience
      Experience(task, context, actions, outcome, verifier_result, cost, prediction)  (keyword fields)
      .to_dict() / Experience.from_dict(d)       round trip
      record(exp) -> int                          writes one CS2 event, kind "experience", returns its id
  tanishi.compiler.passes
      Registry(); .register(name, version, run, check); .get(name, version=None); .names(); .versions(name)
      default_registry()                          holds "pass1", "pass3", "pass4"
      outcome_analysis(exp) -> dict               pure pass-1 analysis: success, surprise, decisive_step
      compile_experience(exp, registry=None) -> list[Emission]
          Emission: pass_name, version, kind, payload, gain, compute, landed, reason
  run(exp) -> list[{"kind", "payload", "gain"}] or None;  check(exp, item) -> (ok: bool, reason: str)
"""
