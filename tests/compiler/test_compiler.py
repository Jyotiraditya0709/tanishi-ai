# ---------------------------------------------------------------- helpers


def make_prediction(success: bool = True, confidence: float = 0.8) -> dict:
    """Written before acting, as the spec says: through the CS5 ledger."""
    expected = {"success": success}
    pid = predictions.predict("task:l1-exam", expected, confidence)
    return {"id": pid, "expected": expected, "confidence": confidence}


def make_experience(*, passed: bool = False, predicted_success: bool = True, confidence: float = 0.8,
                    actions=None, context=None, task: str = "fetch the page title of example.org") -> xp.Experience:
    if actions is None:
        actions = [
            {"tool": "plan", "input": {"goal": "title"}, "output": "ok", "ok": True},
            {"tool": "web_search", "input": {"q": "example.org"}, "output": "timeout", "ok": False},
            {"tool": "answer", "input": {}, "output": "unknown", "ok": True},
        ]
    return xp.Experience(
        task=task,
        context=context if context is not None else {"mood": "neutral", "tools": ["web_search", "plan"]},
        actions=actions,
        outcome={"success": passed, "answer": "Example Domain" if passed else "unknown"},
        verifier_result={"passed": passed, "score": 1.0 if passed else 0.0, "reason": "does not match"},
        cost={"usd": 0.002, "tokens": 900, "seconds": 3.5},
        prediction=make_prediction(predicted_success, confidence),
    )


def events_of(kind: str) -> list:
    return list(events.iter_events(kind=kind))


def run_skill(code: str, test: str) -> bool:
    """Run a candidate's code then its test in a clean interpreter. test_* callables are called."""
    driver = textwrap.dedent(
        """
        import json, sys
        src = json.load(sys.stdin)
        ns = {"__name__": "skill"}
        exec(src["code"], ns)
        exec(src["test"], ns)
        for k, v in list(ns.items()):
            if k.startswith("test_") and callable(v):
                v()
        """
    )
    p = subprocess.run([sys.executable, "-I", "-c", driver], input=json.dumps({"code": code, "test": test}),
                       capture_output=True, text=True, timeout=60, check=False)
    return p.returncode == 0


def item(kind="belief", payload=None, gain=0.5):
    return {"kind": kind, "payload": payload, "gain": gain}


GOOD_BELIEF = {"subject": "tool:web_search", "predicate": "times_out_on", "object": "example.org",
               "confidence": 0.6}


def ok_check(exp, it):
    return True, "fine"


def one_pass_registry(run, check=ok_check, name="custom", version=1):
    reg = passes.Registry()
    reg.register(name, version, run, check)
    return reg


# ---------------------------------------------------------------- acceptance 1: the Experience record


def test_experience_holds_every_field_the_spec_lists():
    exp = make_experience()
    d = exp.to_dict()
    for key in ("task", "context", "actions", "outcome", "verifier_result", "cost", "prediction"):
        assert key in d, key
    assert d["task"] == "fetch the page title of example.org"
    assert [a["tool"] for a in d["actions"]] == ["plan", "web_search", "answer"]  # every action, in order
    assert d["prediction"]["id"].startswith("pred_")
    assert d["verifier_result"]["passed"] is False
    assert d["cost"]["tokens"] == 900


def test_experience_round_trips():
    exp = make_experience(passed=True)
    again = xp.Experience.from_dict(json.loads(json.dumps(exp.to_dict())))
    assert again == exp
    assert again.to_dict() == exp.to_dict()


def test_experience_requires_the_prediction_written_before_acting():
    good = make_experience()
    d = good.to_dict()
    d.pop("prediction")
    with pytest.raises((ValueError, TypeError, KeyError)):
        xp.Experience.from_dict(d)
    d["prediction"] = None
    with pytest.raises((ValueError, TypeError)):
        xp.Experience.from_dict(d)


@pytest.mark.parametrize("field,bad", [("task", ""), ("task", "   "), ("actions", "not a list"),
                                       ("verifier_result", None), ("outcome", None)])
def test_experience_refuses_malformed_fields(field, bad):
    d = make_experience().to_dict()
