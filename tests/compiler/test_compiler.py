def test_default_pass3_check_refuses_a_belief_without_evidence():
    """The real pass 3 check, fed a belief whose evidence has been stripped, must refuse it."""
    real = passes.default_registry().get("pass3")
    exp = make_experience(passed=False)
    items = real.run(exp) or []
    assert items, "pass 3 must emit for a failure with a failing tool"
    stripped = [dict(i, payload={k: v for k, v in i["payload"].items()
                                 if k not in ("evidence", "evidence_event_id")}) for i in items]
    verdicts = [real.check(exp, s) for s in stripped]
    assert all(v[0] is False for v in verdicts)


